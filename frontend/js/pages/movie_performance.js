async function loadGenre() {

  const res = await getGenre();

  if (!res.ok) return;

  const data = res.data;

  const labels  = data.map(d => d.genre_name);
  const revenue = data.map(d => parseFloat(d.total_revenue));
  const rentals = data.map(d => parseInt(d.total_rental));
  const pcts    = data.map(d => parseFloat(d.revenue_pct));

  // KPIs

  const totalRev  = revenue.reduce((a,b) => a+b, 0);
  const totalRent = rentals.reduce((a,b) => a+b, 0);

  buildKPIs(document.getElementById("genre-kpis"), [
    {
      label: "Genres",
      value: data.length
    },
    {
      label: "Total Rentals",
      value: totalRent.toLocaleString(),
      accent: "#B14A36"
    },
    {
      label: "Total Revenue",
      value:
        "$" +
        totalRev.toLocaleString("en-US", {
          minimumFractionDigits: 2
        }),
      accent: "#8C0902"
    },
    {
      label: "Top Genre",
      value: data[0]?.genre_name || "—",
      accent: "#FECE79"
    }
  ]);

  // Revenue Chart

  mkChart(
    "revenue_chart",
    "bar",
    labels,
    [{
      label: "Revenue ($)",
      data: revenue,
      backgroundColor: PALETTE,
      borderRadius: 6
    }],
    {
      scales: {
        y: {
          ticks: {
            callback: v => "$" + v.toLocaleString()
          },
          grid: {
            color: "rgba(0,0,0,.05)"
          }
        },
        x: {
          grid: {
            display: false
          }
        }
      }
    },
    {
      title: "Revenue by Genre",
      category: "genre",
      description: "Shows total revenue generated by each movie genre.",
      xLabel: "Genre",
      yLabel: "Revenue ($)",
      keywords: [
        "genre",
        "revenue",
        "sales",
        "earnings"
      ]
    }
  );

  // Rental Chart

  mkChart(
    "rental_chart",
    "bar",
    labels,
    [{
      label: "Rentals",
      data: rentals,
      backgroundColor: PALETTE.slice(1),
      borderRadius: 6
    }],
    {
      scales: {
        y: {
          ticks: {
            callback: v => v.toLocaleString()
          },
          grid: {
            color: "rgba(0,0,0,.05)"
          }
        },
        x: {
          grid: {
            display: false
          }
        }
      }
    },
    {
      title: "Rental Count by Genre",
      category: "genre",
      description: "Displays number of rentals completed per genre.",
      xLabel: "Genre",
      yLabel: "Rental Count",
      keywords: [
        "genre",
        "rentals",
        "frequency",
        "usage"
      ]
    }
  );

  // Share Chart

  mkChart(
    "share_chart",
    "doughnut",
    labels,
    [{
      data: pcts,
      backgroundColor: PALETTE,
      borderWidth: 2,
      borderColor: "#fff"
    }],
    {
      legend: true,
      extra: {
        plugins: {
          legend: {
            position: "right",
            labels: {
              boxWidth: 12,
              font: {
                size: 11
              }
            }
          },
          tooltip: {
            callbacks: {
              label: ctx =>
                `${ctx.label}: ${ctx.parsed.toFixed(1)}%`
            }
          }
        },
        cutout: "52%"
      }
    },
    {
      title: "Revenue Share by Genre",
      category: "genre",
      description: "Percentage contribution of each genre to total revenue.",
      xLabel: "Genre",
      yLabel: "Revenue Share %",
      keywords: [
        "genre",
        "market share",
        "distribution",
        "percentage"
      ]
    }
  );

  // Best Film Table

  const table = document.getElementById("best-film-table");

  if (table) {

    table.innerHTML = `
      <div class="section-label">Top Film per Genre</div>

      <div class="data-table-wrap">

        <table class="data-table">

          <thead>
            <tr>
              <th>Genre</th>
              <th>Best Film</th>
              <th>Revenue</th>
            </tr>
          </thead>

          <tbody>

            ${data.map(d => `
              <tr>
                <td>${d.genre_name}</td>

                <td
                  style="
                    max-width:140px;
                    overflow:hidden;
                    text-overflow:ellipsis;
                    white-space:nowrap
                  "
                >
                  ${d.best_film}
                </td>

                <td>
                  $${parseFloat(d.total_revenue).toLocaleString(
                    "en-US",
                    { minimumFractionDigits: 2 }
                  )}
                </td>
              </tr>
            `).join("")}

          </tbody>

        </table>

      </div>
    `;
  }
}

