function mkChart(
  id,
  type,
  labels,
  datasets,
  opts = {},
  meta = {}
) {
  const ctx = document.getElementById(id)?.getContext("2d");
  if (!ctx) return null;

  const chart = new Chart(ctx, {
    type,
    data: {
      labels,
      datasets
    },
    options: {
      responsive: true,
      maintainAspectRatio: false,

      plugins: {
        legend: {
          display: opts.legend ?? false
        }
      },

      scales: opts.scales,
      ...opts.extra
    }
  });

  ChartRegistry.register(id, chart, {
    page: "movie",
    title: meta.title || id,
    category: meta.category || "general",
    description: meta.description || "",
    xLabel: meta.xLabel || "",
    yLabel: meta.yLabel || "",
    keywords: meta.keywords || [],
    ...meta
  });

  return chart;
}

function buildKPIs(container, items) {
  container.innerHTML = items.map(({ label, value, accent }) => `
    <div class="kpi-card" style="--accent:${accent || "var(--clr-gold)"}">
      <div class="kpi-label">${label}</div>
      <div class="kpi-value">${value}</div>
    </div>
  `).join("");
}

