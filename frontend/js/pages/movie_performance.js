// ─────────────────────────────────────────────────────────────
// Genre × Rating
// ─────────────────────────────────────────────────────────────

async function loadGenreRating() {

  const res = await getGenreRating();

  if (!res.ok) return;

  const raw = res.data;

  const genres = [
    ...new Set(raw.map(r => r.genre_name))
  ].sort();

  const ratings = [
    "G",
    "PG",
    "PG-13",
    "R",
    "NC-17"
  ];

  const datasets = ratings.map(rating => ({
    label: rating,

    data: genres.map(genre => {

      const match = raw.find(
        r =>
          r.genre_name === genre &&
          r.rating === rating
      );

      return match
        ? parseInt(match.rental_count)
        : 0;
    }),

    backgroundColor:
      RATING_COLORS[rating] || "#888",

    borderRadius: 4
  }));

  mkChart(
    "genre_rating_chart",
    "bar",
    genres,
    datasets,
    {
      legend: true
    },
    {
      title: "Genre × Rating Distribution",
      category: "combined",
      description:
        "Rental distribution by genre and movie rating.",
      xLabel: "Genre",
      yLabel: "Rental Count",
      keywords: [
        "genre",
        "rating",
        "distribution",
        "comparison"
      ]
    }
  );
}

// ─────────────────────────────────────────────────────────────
// Rental Form
// ─────────────────────────────────────────────────────────────

async function loadRentalForm() {

  const [filmsRes, custsRes] = await Promise.all([
    getFilms(),
    getCustomers()
  ]);

  if (filmsRes.ok) {

    const sel = document.getElementById("rental-film");

    filmsRes.data.forEach(f => {

      const opt = document.createElement("option");

      opt.value = f.film_id;
      opt.textContent = `${f.title} (${f.genre})`;

      sel.appendChild(opt);

    });
  }

  if (custsRes.ok) {

    const sel = document.getElementById("rental-customer");

    custsRes.data.forEach(c => {

      const opt = document.createElement("option");

      opt.value = c.customer_id;
      opt.textContent = c.name;

      sel.appendChild(opt);

    });
  }

  document
    .getElementById("btn-add-rental")
    .addEventListener("click", async () => {

      const film_id =
        document.getElementById("rental-film").value;

      const customer_id =
        document.getElementById("rental-customer").value;

      const amount = parseFloat(
        document.getElementById("rental-amount").value
      );

      const msgEl =
        document.getElementById("rental-msg");

      msgEl.innerHTML = `
        <div class="loading-state" style="padding:.5rem">
          <div class="spinner"></div>
          Submitting…
        </div>
      `;

      try {

        const res = await postRental({
          film_id: parseInt(film_id),
          customer_id: parseInt(customer_id),
          amount
        });

        if (res.ok) {

          msgEl.innerHTML = `
            <div class="alert success">
              <div class="alert-icon">✓</div>
              <div class="alert-body">${res.message}</div>
            </div>
          `;

          setTimeout(() => {
            loadGenre();
            loadRating();
          }, 1000);

        } else {

          msgEl.innerHTML = `
            <div class="alert error">
              <div class="alert-icon">!</div>
              <div class="alert-body">${res.error}</div>
            </div>
          `;
        }

      } catch (e) {

        msgEl.innerHTML = `
          <div class="alert error">
            <div class="alert-icon">!</div>
            <div class="alert-body">${e.message}</div>
          </div>
        `;
      }

    });
}

